"""Write web/langs.js from dub/languages.py so the picker and the API accept the same languages."""
import json
from pathlib import Path

from dub.languages import LANGUAGES

OUT = Path(__file__).resolve().parent.parent / "web" / "langs.js"


def render() -> str:
    table = {code: native for code, (_, native) in LANGUAGES.items()}
    return ("// Generated by tools/gen_langs_js.py from dub/languages.py. Do not edit by hand.\n"
            f"export const LANG = {json.dumps(table, ensure_ascii=False, indent=1)};\n")


if __name__ == "__main__":
    OUT.write_text(render())
    print(f"{OUT} · {len(LANGUAGES)} languages")
